// Adds a translucent ShareActivity: the Android share target that shows Hang's sheet *over* the
// app you shared from. It hosts the JS component "ShareSheet" (registered in index.ts) and passes
// the share intent to it as initial props. Kept as a config plugin so android/ stays generated.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withAndroidStyles, withDangerousMod } = require('expo/config-plugins');

const ACTIVITY = '.ShareActivity';
const THEME = 'Theme.Hang.Share';
const SHARED_TYPES = ['text/plain', 'image/*'];

const shareActivitySource = (pkg) => `package ${pkg}

import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Bundle

import com.facebook.react.ReactActivity
import com.facebook.react.ReactActivityDelegate
import com.facebook.react.defaults.DefaultNewArchitectureEntryPoint.fabricEnabled
import com.facebook.react.defaults.DefaultReactActivityDelegate

import expo.modules.ReactActivityDelegateWrapper

/** Generated by plugins/withShareActivity.js. Do not edit; change the plugin instead. */
class ShareActivity : ReactActivity() {
  private val openedAt = System.currentTimeMillis()

  override fun getMainComponentName(): String = "ShareSheet"

  override fun createReactActivityDelegate(): ReactActivityDelegate {
    return ReactActivityDelegateWrapper(
      this,
      BuildConfig.IS_NEW_ARCHITECTURE_ENABLED,
      object : DefaultReactActivityDelegate(this, mainComponentName, fabricEnabled) {
        override fun getLaunchOptions(): Bundle? = shareProps(intent, openedAt)
      })
  }

  /** Root of its own task: the default would move the task to back on Android 12+. Close for real. */
  override fun invokeDefaultOnBackPressed() {
    finish()
  }

  override fun finish() {
    super.finish()
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
      overrideActivityTransition(OVERRIDE_TRANSITION_CLOSE, 0, 0)
    } else {
      @Suppress("DEPRECATION")
      overridePendingTransition(0, 0)
    }
  }
}

private fun shareProps(intent: Intent?, openedAt: Long): Bundle = Bundle().apply {
  putDouble("openedAt", openedAt.toDouble())
  putString("action", intent?.action)
  putString("type", intent?.type)
  putString("text", intent?.getStringExtra(Intent.EXTRA_TEXT))
  putString("subject", intent?.getStringExtra(Intent.EXTRA_SUBJECT))
  putString("title", intent?.getStringExtra(Intent.EXTRA_TITLE))
  putString("stream", streamUri(intent)?.toString())
}

private fun streamUri(intent: Intent?): Uri? = when {
  intent == null -> null
  Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU -> intent.getParcelableExtra(Intent.EXTRA_STREAM, Uri::class.java)
  else -> @Suppress("DEPRECATION") intent.getParcelableExtra(Intent.EXTRA_STREAM)
}
`;

function withShareActivitySource(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('withShareActivity: android.package is required in app.json');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'ShareActivity.kt'), shareActivitySource(pkg));
      return cfg;
    },
  ]);
}

function item(name, value) {
  return { $: { name }, _: value };
}

function withShareTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults.resources.style ?? [];
    const others = styles.filter((style) => style.$.name !== THEME);
    const theme = {
      $: { name: THEME, parent: 'Theme.AppCompat.DayNight.NoActionBar' },
      item: [
        item('android:windowIsTranslucent', 'true'),
        item('android:windowBackground', '@android:color/transparent'),
        item('android:windowNoTitle', 'true'),
        item('android:backgroundDimEnabled', 'false'),
        item('android:windowAnimationStyle', '@null'),
        item('android:statusBarColor', '@android:color/transparent'),
        item('android:navigationBarColor', '@android:color/transparent'),
      ],
    };
    cfg.modResults.resources.style = [...others, theme];
    return cfg;
  });
}

function shareActivityEntry() {
  return {
    $: {
      'android:name': ACTIVITY,
      'android:theme': `@style/${THEME}`,
      'android:exported': 'true',
      // Own empty-affinity task: finishing returns to the app you shared from, never to Hang's main UI.
      'android:taskAffinity': '',
      'android:excludeFromRecents': 'true',
      'android:windowSoftInputMode': 'adjustResize',
      'android:configChanges': 'keyboard|keyboardHidden|orientation|screenSize|screenLayout|uiMode',
    },
    'intent-filter': [
      {
        action: [{ $: { 'android:name': 'android.intent.action.SEND' } }],
        category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
        data: SHARED_TYPES.map((mimeType) => ({ $: { 'android:mimeType': mimeType } })),
      },
    ],
  };
}

function withShareManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    if (!application) throw new Error('withShareActivity: no <application> in AndroidManifest.xml');
    const others = (application.activity ?? []).filter((a) => a.$['android:name'] !== ACTIVITY);
    application.activity = [...others, shareActivityEntry()];
    return cfg;
  });
}

module.exports = function withShareActivity(config) {
  return withShareManifest(withShareTheme(withShareActivitySource(config)));
};
